"""Black-box contracts for the workspace Lisp lookup and batch runner."""
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]
COMMAND = ROOT / "scripts/elisp.py"

LIBRARY = r''';;; fixture-lib.el --- Fixture library -*- lexical-binding: t; -*-

(cl-defstruct (fixture-point (:constructor fixture-point-create)) x y)
(defmacro fixture-define-widget (name &rest body) `(defvar ,name (list ,@body)))

(defun fixture-lib-value ()
  "Return a value; the docstring mentions (unbalanced ( parens."
  (let ((open ?\() (close ?\)) (text "a ) string"))
    ;; A comment with ) parens
    (list open close text (fixture-lib-helper))))

(defun fixture-lib-helper ()
  (+ 1 2))

(fixture-define-widget fixture-lib-widget
  :value (fixture-lib-helper))

;; (fixture-lib-helper) in a comment is not a reference.
(defvar fixture-lib-count (fixture-lib-helper))

(provide 'fixture-lib)
'''


def elisp(root, *args, timeout=60, input=None):
    return subprocess.run([sys.executable, str(COMMAND), "--root", str(root), *args],
                          capture_output=True, text=True, timeout=timeout, input=input)


class ElispTool(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.directory = tempfile.TemporaryDirectory(prefix="taf-elisp-tests-")
        cls.root = Path(cls.directory.name)
        (cls.root / "scripts").mkdir()
        shutil.copy(ROOT / "scripts/ecosystem.el", cls.root / "scripts/ecosystem.el")
        (cls.root / "workspace.json").write_text(json.dumps({"repositories": {"fixture": {}}}))
        (cls.root / "fixture/lisp").mkdir(parents=True)
        (cls.root / "fixture/lisp/fixture-lib.el").write_text(LIBRARY)
        (cls.root / "fixture/tests").mkdir()
        (cls.root / "fixture/tests/fixture-lib-tests.el").write_text(
            "(ert-deftest fixture-lib-helper-test ()\n  (should (= 3 (fixture-lib-helper))))\n")

    @classmethod
    def tearDownClass(cls):
        cls.directory.cleanup()

    def test_def_prints_complete_forms_with_location(self):
        result = elisp(self.root, "def", "fixture-lib-value", "fixture-lib-widget")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn(";; fixture/lisp/fixture-lib.el:6-10\n(defun fixture-lib-value ()", result.stdout)
        self.assertIn("(list open close text (fixture-lib-helper))))\n", result.stdout)
        self.assertNotIn("(defun fixture-lib-helper", result.stdout)
        self.assertIn(";; fixture/lisp/fixture-lib.el:15-16\n(fixture-define-widget fixture-lib-widget", result.stdout)

    def test_def_resolves_struct_accessors_and_suggests_missing_names(self):
        accessor = elisp(self.root, "def", "fixture-point-x")
        self.assertEqual(accessor.returncode, 0)
        self.assertIn("generated by cl-defstruct", accessor.stdout)
        self.assertIn("(cl-defstruct (fixture-point", accessor.stdout)
        missing = elisp(self.root, "def", "fixture-lib-helpr")
        self.assertEqual(missing.returncode, 1)
        self.assertRegex(missing.stdout, r"no definition found; similar: .*fixture-lib-helper")

    def test_def_truncates_long_forms_with_a_continuation_hint(self):
        result = elisp(self.root, "def", "fixture-lib-value", "--max-lines", "2")
        self.assertIn("more lines (through line 10); rerun with --max-lines 0", result.stdout)
        self.assertNotIn("(list open close", result.stdout)

    def test_refs_group_by_enclosing_definition(self):
        result = elisp(self.root, "refs", "fixture-lib-helper")
        self.assertEqual(result.returncode, 0, result.stderr)
        lines = result.stdout.splitlines()
        self.assertEqual(lines[0], ";; fixture-lib-helper: 4 references in 2 files; "
                                   "defined at fixture/lisp/fixture-lib.el:12")
        self.assertIn("  defun fixture-lib-value: 10", lines)
        self.assertIn("  fixture-define-widget fixture-lib-widget: 16", lines)
        self.assertIn("  defvar fixture-lib-count: 19", lines)
        self.assertIn("  ert-deftest fixture-lib-helper-test: 2", lines)
        self.assertLess(lines.index("fixture/lisp/fixture-lib.el"), lines.index("fixture/tests/fixture-lib-tests.el"))

    def test_run_requires_workspace_features_and_prints_plain_bounded_values(self):
        form = ("(list (fixture-lib-helper) (propertize \"abc\" 'face 'bold)"
                " (let ((cycle (list 1 2))) (setcdr (cdr cycle) cycle) cycle))")
        result = elisp(self.root, "run", "-p", "fixture-lib", "-e", form)
        self.assertEqual(result.returncode, 0, result.stdout)
        value, summary = result.stdout.splitlines()[-2:]
        self.assertTrue(value.startswith('(3 "abc" (1 2 . #1='), value)
        self.assertRegex(summary, r"^status=ok exit=0 seconds=[\d.]+ peak_rss_mb=\d+$")

    def test_run_keeps_load_and_call_order(self):
        script = self.root / "hello.el"
        script.write_text(";;; -*- lexical-binding: t; -*-\n(defun hello-run () (princ \"hello\\n\"))\n")
        result = elisp(self.root, "run", "-l", str(script), "-f", "hello-run")
        self.assertEqual(result.returncode, 0, result.stdout)
        self.assertIn("hello\n", result.stdout)

    def test_run_reports_errors_timeouts_and_usage(self):
        failed = elisp(self.root, "run", "-e", "(car 1)")
        self.assertNotEqual(failed.returncode, 0)
        self.assertIn("wrong-type-argument", failed.stdout)
        self.assertRegex(failed.stdout.splitlines()[-1], r"^status=error exit=\d+ ")
        stuck = elisp(self.root, "run", "-e", "(while t)", "--timeout", "1")
        self.assertEqual(stuck.returncode, 124)
        self.assertTrue(stuck.stdout.splitlines()[-1].startswith("status=timeout exit=124 "))
        usage = elisp(self.root, "run")
        self.assertEqual(usage.returncode, 2)
        self.assertIn("error=usage", usage.stderr)

    def test_run_cuts_large_output_and_keeps_the_full_log(self):
        result = elisp(self.root, "run", "-e", "(dotimes (i 5000) (message \"line %d\" i))",
                       "--max-output-kb", "2")
        self.assertEqual(result.returncode, 0)
        self.assertIn("lines omitted; full output:", result.stdout)
        log = Path(re.search(r"log=(\S+)", result.stdout.splitlines()[-1]).group(1))
        try:
            self.assertIn("line 2500", log.read_text())
            self.assertNotIn("line 2500\n", result.stdout)
        finally:
            log.unlink()


    def test_check_ignores_delimiters_hidden_in_strings_comments_and_chars(self):
        good = elisp(self.root, "check", str(self.root / "fixture/lisp/fixture-lib.el"))
        self.assertEqual(good.returncode, 0, good.stdout)
        self.assertTrue(good.stdout.endswith(": ok\n"), good.stdout)
        stdin = elisp(self.root, "check", "-", input='(list "a ) b" ?\\) ) ;; )\n')
        self.assertEqual(stdin.returncode, 0, stdin.stdout)
        self.assertTrue(stdin.stdout.endswith("-: ok\n"), stdin.stdout)

    def test_check_reports_unclosed_and_unmatched_delimiters(self):
        truncated = self.root / "truncated.el"
        truncated.write_text('(defun truncated ()\n  (list "a ) b" ?\\) ; )\n')
        result = elisp(self.root, "check", str(truncated))
        self.assertEqual(result.returncode, 1)
        self.assertEqual(result.stdout.strip(),
                         f"{truncated}: 2 unclosed '(' form(s), innermost at line 2")
        unmatched = self.root / "unmatched.el"
        unmatched.write_text("(defun unmatched ())\n)\n")
        result = elisp(self.root, "check", str(unmatched))
        self.assertEqual(result.returncode, 1)
        self.assertEqual(result.stdout.strip(), f"{unmatched}: line 2: unexpected ')'")
        mixed = elisp(self.root, "check", "-", input="(let ((x 1])\n")
        self.assertEqual(mixed.returncode, 1)
        self.assertIn("line 1: unexpected ']'", mixed.stdout)

    def test_check_reports_unreadable_files(self):
        missing = self.root / "missing.el"
        result = elisp(self.root, "check", str(missing))
        self.assertEqual(result.returncode, 1)
        self.assertIn("cannot read", result.stderr)


if __name__ == "__main__":
    unittest.main()
