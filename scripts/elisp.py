#!/usr/bin/env python3
"""Look up and run Emacs Lisp across the workspace checkouts.

def   print the complete source form of each named definition
refs  list the references to a symbol grouped by enclosing definition
run   run Emacs in batch with the workspace loaded, bounded printing and
      time, memory and output limits
"""
from __future__ import annotations

import argparse
import difflib
import os
from pathlib import Path
import re
import signal
import subprocess
import sys
import tempfile
import time

ROOT = Path(__file__).resolve().parents[1]
CONSTITUENT = r"\w\-*+/:<>=!?$%&.~^"
DEF_HEAD = r"\((?:[\w-]*-)?def[\w*-]*\s+'?"
LIBRARY_DIRS = {"lisp", "."}


def sources(root: Path) -> list[Path]:
    """Workspace Lisp sources, skipping hidden directories (VCS data, worktrees)."""
    found = []
    for directory, subdirs, files in os.walk(root):
        subdirs[:] = sorted(d for d in subdirs if not d.startswith("."))
        found.extend(Path(directory, name) for name in sorted(files) if name.endswith(".el"))
    return found


def form_end(text: str, start: int) -> int | None:
    """End offset of the balanced form opening at START, honoring strings, comments and ?chars."""
    depth, index, size = 0, start, len(text)
    while index < size:
        char = text[index]
        if char == ";":
            index = text.find("\n", index)
            if index == -1:
                return None
        elif char == '"':
            index += 1
            while index < size and text[index] != '"':
                index += 2 if text[index] == "\\" else 1
        elif char == "?" and not re.match(f"[{CONSTITUENT}]", text[index - 1]):
            index += 2 if text[index + 1:index + 2] == "\\" else 1
        elif char == "\\":
            index += 1
        elif char in "([":
            depth += 1
        elif char in ")]":
            depth -= 1
            if depth == 0:
                return index + 1
        index += 1
    return None


def line_of(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


def relative(path: Path, root: Path) -> str:
    return str(path.relative_to(root))


def symbol_pattern(symbol: str) -> re.Pattern[str]:
    return re.compile(f"(?<![{CONSTITUENT}]){re.escape(symbol)}(?![{CONSTITUENT}])")


def rank(path: Path, root: Path) -> tuple[int, str]:
    """Library code first, then tests, benchmarks and examples."""
    parts = path.relative_to(root).parts
    kind = parts[1] if len(parts) > 2 else "."
    return (0 if kind in LIBRARY_DIRS else 1, str(path))


def definitions(texts: dict[Path, str], symbol: str) -> list[tuple[Path, int]]:
    pattern = re.compile(DEF_HEAD + re.escape(symbol) + f"(?![{CONSTITUENT}])")
    return [(path, match.start()) for path, text in texts.items() for match in pattern.finditer(text)]


def suggestions(texts: dict[Path, str], symbol: str) -> list[str]:
    names = {m.group(1) for text in texts.values()
             for m in re.finditer(DEF_HEAD + f"([{CONSTITUENT}]+)", text)}
    close = difflib.get_close_matches(symbol, names, n=5, cutoff=0.75)
    parts = [part for part in symbol.split("-") if len(part) > 3]
    related = sorted(n for n in names if parts and all(p in n for p in parts[-2:]) and n not in close)
    return close + related[:5 - len(close)]


def command_def(args: argparse.Namespace) -> int:
    root = args.root.resolve()
    texts = {path: path.read_text(errors="replace") for path in sources(root)}
    missing = 0
    for symbol in args.symbols:
        found = sorted(definitions(texts, symbol), key=lambda item: rank(item[0], root))
        if not found:
            # Struct accessors and predicates have no form of their own.
            owners = [(path, m.start()) for path, text in texts.items()
                      for m in re.finditer(r"\(cl-defstruct\s+\(?([" + CONSTITUENT + "]+)", text)
                      if symbol.startswith(m.group(1) + "-")]
            if owners:
                print(f";; {symbol}: generated by cl-defstruct")
                found = owners
            else:
                missing += 1
                near = suggestions(texts, symbol)
                print(f";; {symbol}: no definition found" + (f"; similar: {' '.join(near)}" if near else ""))
                continue
        for path, start in found[:args.limit]:
            text = texts[path]
            end = form_end(text, start)
            if end is None:
                following = re.compile(r"^\(", re.M).search(text, start + 1)
                end = following.start() if following else len(text)
            first, last = line_of(text, start), line_of(text, end)
            lines = text[start:end].splitlines()
            print(f";; {relative(path, root)}:{first}-{last}")
            shown = lines if args.max_lines == 0 else lines[:args.max_lines]
            print("\n".join(shown))
            if len(shown) < len(lines):
                print(f";; ... {len(lines) - len(shown)} more lines (through line {last}); rerun with --max-lines 0")
        if len(found) > args.limit:
            print(f";; {symbol}: {len(found) - args.limit} more definitions omitted; raise --limit")
    return 1 if missing else 0


def top_level_forms(text: str) -> list[tuple[int, int, str]]:
    """Spans of top-level forms with a short label such as `defun name'."""
    forms, index = [], 0
    for match in re.finditer(r"^\(", text, re.M):
        if match.start() < index:
            continue
        end = form_end(text, match.start()) or len(text)
        head = re.match(r"\(([^\s()]+)(?:\s+'?\(?([^\s()]+))?", text[match.start():match.start() + 200])
        label = " ".join(filter(None, head.groups())) if head else "form"
        forms.append((match.start(), end, label))
        index = end
    return forms


def command_refs(args: argparse.Namespace) -> int:
    root = args.root.resolve()
    pattern = symbol_pattern(args.symbol)
    define = re.compile(DEF_HEAD + re.escape(args.symbol) + f"(?![{CONSTITUENT}])")
    groups, defined, total = [], [], 0
    for path in sources(root):
        text = path.read_text(errors="replace")
        hits = [m.start() for m in pattern.finditer(text)
                if not text[text.rfind("\n", 0, m.start()) + 1:m.start()].lstrip().startswith(";")]
        if not hits:
            continue
        own = {m.start() + m.group(0).rfind(args.symbol) for m in define.finditer(text)}
        defined += [f"{relative(path, root)}:{line_of(text, offset)}" for offset in sorted(own)]
        by_form: dict[str, list[int]] = {}
        forms = top_level_forms(text)
        for offset in hits:
            if offset in own:
                continue
            label = next((label for start, end, label in forms if start <= offset < end), "top level")
            by_form.setdefault(label, []).append(line_of(text, offset))
        if by_form:
            count = sum(map(len, by_form.values()))
            total += count
            groups.append((rank(path, root)[0], -count, relative(path, root), by_form))
    files = len(groups)
    print(f";; {args.symbol}: {total} references in {files} files"
          + (f"; defined at {', '.join(defined)}" if defined else "; no definition found"))
    for _, _, name, by_form in sorted(groups)[:args.limit]:
        print(name)
        for label, lines in by_form.items():
            print(f"  {label}: {','.join(map(str, lines))}")
    if files > args.limit:
        print(f";; {files - args.limit} more files omitted; raise --limit")
    return 0 if total or defined else 1


PRELUDE = """(progn
  (setq print-circle t print-length 50 print-level 8 print-escape-newlines t)
  (defun elisp-run--plain (value depth seen)
    "Copy VALUE with property-free strings, within the printer's own limits."
    (cond ((stringp value) (substring-no-properties value))
          ((or (> depth 8) (gethash value seen)
               (not (or (consp value) (and (vectorp value) (not (recordp value))))))
           value)
          ((consp value)
           (let ((out nil) (n 0) (tail value))
             (while (and (consp tail) (< n 50) (not (gethash tail seen)))
               (puthash tail t seen)
               (push (elisp-run--plain (car tail) (1+ depth) seen) out)
               (setq tail (cdr tail) n (1+ n)))
             (setq out (nreverse out))
             (setcdr (last out) (if (stringp tail) (substring-no-properties tail) tail))
             out))
          (t (puthash value t seen)
             (apply #'vector (mapcar (lambda (item) (elisp-run--plain item (1+ depth) seen))
                                     (append value nil))))))
  (defun elisp-run--print (value)
    (princ (if (stringp value) (substring-no-properties value)
             (prin1-to-string (elisp-run--plain value 0 (make-hash-table :test 'eq)))))
    (terpri)))"""


class Ordered(argparse.Action):
    """Keep -l/-f/-e in command-line order, as Emacs itself does."""

    def __call__(self, parser, namespace, values, option_string=None):
        namespace.actions.append((self.dest, values))


def rss_kb(pid: int) -> int:
    result = subprocess.run(["ps", "-o", "rss=", "-p", str(pid)], capture_output=True, text=True)
    return int(result.stdout.strip() or 0)


def emit(log: Path, limit_kb: int) -> bool:
    """Print LOG, or its head and tail when it exceeds LIMIT_KB; return whether it was cut."""
    data = log.read_text(errors="replace")
    if len(data.encode()) <= limit_kb * 1024:
        sys.stdout.write(data)
        return False
    lines = data.splitlines()
    head, tail = lines[:40], lines[-80:]
    omitted = len(lines) - len(head) - len(tail)
    sys.stdout.write("\n".join(head) + f"\n... [{omitted} lines omitted; full output: {log}]\n"
                     + "\n".join(tail) + "\n")
    return True


def command_run(args: argparse.Namespace) -> int:
    if not args.actions:
        print("error=usage run needs at least one -e FORM, -l FILE or -f FUNCTION", file=sys.stderr)
        return 2
    root = args.root.resolve()
    command = [args.emacs, "-Q", "--batch", "-l", str(root / "scripts/ecosystem.el"),
               "--eval", "(etaf-ecosystem-setup)", "--eval", PRELUDE]
    for directory in args.load_path:
        command += ["-L", directory]
    if args.package:
        command += ["--eval", "(etaf-ecosystem-require %s)" % " ".join(f"'{name}" for name in args.package)]
    for kind, value in args.actions:
        command += {"load": ["-l", value], "funcall": ["-f", value],
                    "eval": ["--eval", f"(elisp-run--print (progn {value}\n))"]}[kind]
    handle, name = tempfile.mkstemp(prefix="elisp-run-", suffix=".log")
    log = Path(name)
    started, peak, status = time.monotonic(), 0, "ok"
    with os.fdopen(handle, "w") as output:
        process = subprocess.Popen(command, stdout=output, stderr=subprocess.STDOUT,
                                   stdin=subprocess.DEVNULL, start_new_session=True)
        while process.poll() is None:
            time.sleep(0.1)
            peak = max(peak, rss_kb(process.pid))
            if time.monotonic() - started > args.timeout:
                status = "timeout"
            elif peak > args.max_rss_mb * 1024:
                status = "memory"
            elif log.stat().st_size > args.max_output_kb * 1024 * 64:
                status = "output"
            if status != "ok":
                os.killpg(process.pid, signal.SIGKILL)
                process.wait()
                break
    cut = emit(log, args.max_output_kb)
    code = process.returncode if status == "ok" else 124
    if status == "ok" and code != 0:
        status = "error"
    fields = [f"status={status}", f"exit={code}", f"seconds={time.monotonic() - started:.2f}",
              f"peak_rss_mb={peak // 1024}"]
    if cut:
        fields.append(f"log={log}")
    else:
        log.unlink()
    print(" ".join(fields))
    return code


def main() -> int:
    parser = argparse.ArgumentParser(prog="elisp.py", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=ROOT, help="workspace checkout (default: this one)")
    commands = parser.add_subparsers(dest="command", required=True)

    define = commands.add_parser("def", help="print the source form of each definition")
    define.add_argument("symbols", nargs="+", metavar="SYMBOL")
    define.add_argument("--max-lines", type=int, default=250, help="lines per form; 0 prints all")
    define.add_argument("--limit", type=int, default=8, help="definitions per symbol")
    define.set_defaults(handler=command_def)

    refs = commands.add_parser("refs", help="list references grouped by enclosing definition")
    refs.add_argument("symbol", metavar="SYMBOL")
    refs.add_argument("--limit", type=int, default=40, help="files to list")
    refs.set_defaults(handler=command_refs)

    run = commands.add_parser("run", help="run batch Emacs with the workspace on load-path")
    run.set_defaults(handler=command_run, actions=[])
    run.add_argument("-p", "--package", action="append", default=[], metavar="FEATURE",
                     help="require FEATURE from the workspace (repeatable)")
    run.add_argument("-L", dest="load_path", action="append", default=[], metavar="DIR",
                     help="extra load-path directory, e.g. a tests directory")
    run.add_argument("-l", dest="load", action=Ordered, metavar="FILE", help="load FILE")
    run.add_argument("-f", dest="funcall", action=Ordered, metavar="FUNCTION", help="call FUNCTION")
    run.add_argument("-e", dest="eval", action=Ordered, metavar="FORM",
                     help="evaluate FORM and print its value without text properties")
    run.add_argument("--timeout", type=float, default=120, help="seconds (default 120)")
    run.add_argument("--max-rss-mb", type=int, default=2048, help="memory limit (default 2048)")
    run.add_argument("--max-output-kb", type=int, default=32,
                     help="print head and tail beyond this size (default 32)")
    run.add_argument("--emacs", default=os.environ.get("EMACS", "emacs"))
    args = parser.parse_args()
    return args.handler(args)


if __name__ == "__main__":
    sys.exit(main())
