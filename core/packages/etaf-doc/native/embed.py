"""Generate C source and header embedding vendored JS bundles and the host bridge.

Inspired by LuciusChen/pele.el's scripts/embed.py; emits a separate bundles.c
unit so incremental C edits to etaf_md_typeset.c do not reparse the JS arrays.
"""
from __future__ import annotations

import pathlib
import sys


def main(argv: list[str]) -> int:
    if len(argv) != 6:
        print(
            "usage: embed.py <out.h> <out.c> <pele.global.js> <mathjax-tex-svg.global.js> <bridge.js>",
            file=sys.stderr,
        )
        return 2

    header_path, source_path, pele_path, mathjax_path, bridge_path = map(pathlib.Path, argv[1:])
    entries = (
        ("etaf_md_pele_bundle", pele_path),
        ("etaf_md_mathjax_bundle", mathjax_path),
        ("etaf_md_bridge_bundle", bridge_path),
    )

    header_path.parent.mkdir(parents=True, exist_ok=True)
    source_path.parent.mkdir(parents=True, exist_ok=True)

    with header_path.open("w", encoding="utf-8") as header:
        header.write("/* Generated by embed.py; do not edit. */\n")
        header.write("#ifndef ETAF_MD_BUNDLES_H\n")
        header.write("#define ETAF_MD_BUNDLES_H\n")
        header.write("#include <stddef.h>\n")
        for name, _ in entries:
            header.write(f"extern const unsigned char {name}[];\n")
            header.write(f"extern const size_t {name}_len;\n")
        header.write("#endif\n")

    with source_path.open("w", encoding="utf-8") as output:
        output.write("/* Generated by embed.py; do not edit. */\n")
        output.write('#include "bundles.h"\n')
        for name, path in entries:
            data = path.read_bytes()
            output.write(f"const unsigned char {name}[] = {{\n")
            for offset in range(0, len(data), 32):
                chunk = data[offset : offset + 32]
                output.write(",".join(str(b) for b in chunk) + ",\n")
            output.write(f"0\n}};\nconst size_t {name}_len = {len(data)}u;\n")

    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
