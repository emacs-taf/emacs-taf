#!/usr/bin/env python3
"""Generate a single autoloads file for local ETAF source development.

Scans every monorepo package root entry (`<pkg>/<pkg>.el`) plus optional
companion checkout roots (`--extra DIR`) using Emacs's built-in `loaddefs-gen'
so local `'source` mode gets the exact same zero-startup-cost autoloads and
`etaf-app-define' declarations that `package.el` generates for ELPA installs.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

import workspace_layout  # noqa: E402


ELISP_GENERATOR = r"""
(progn
(require 'cl-lib)
(require 'loaddefs-gen)
(require 'json)
(require 'subr-x)

(let* ((spec-file (getenv "DEV_AUTOLOADS_SPEC"))
       (output-file (getenv "DEV_AUTOLOADS_OUT"))
       (spec (with-temp-buffer
               (insert-file-contents spec-file)
               (json-parse-buffer :object-type 'alist :array-type 'list)))
       (entries (alist-get 'entries spec))
       (form-count 0)
       (pkg-count 0))
  (make-directory (file-name-directory output-file) t)
  (with-temp-file output-file
    (insert ";;; dev-autoloads.el --- Generated ETAF local source autoloads  -*- lexical-binding: t; no-byte-compile: t; -*-\n")
    (insert ";; Generated by scripts/dev-autoloads.py; do not edit by hand.\n\n")
    (insert "(dolist (dir '(\n")
    (dolist (entry entries)
      (insert (format "  %S\n" (alist-get 'dir entry))))
    (insert "  ))\n")
    (insert "  (when (file-directory-p dir)\n")
    (insert "    (add-to-list 'load-path dir)))\n\n")
    (let ((print-level nil)
          (print-length nil)
          (print-quoted t))
      (dolist (entry entries)
        (let* ((name (alist-get 'name entry))
               (dir (alist-get 'dir entry))
               (file (alist-get 'file entry))
               (virtual-out (expand-file-name "dev-autoloads.el" dir))
               (parsed (condition-case err
                           (loaddefs-generate--parse-file file virtual-out)
                         (error
                          (message "dev-autoloads: skipping %s (%s)"
                                   file (error-message-string err))
                          nil))))
          (setq pkg-count (1+ pkg-count))
          (when parsed
            (insert (format ";;;; %s (%s)\n\n" name file))
            (insert (format "(let ((load-file-name %S))\n" file))
            (dolist (item parsed)
              (let ((body (nth 2 item)))
                (setq form-count (1+ form-count))
                (cond
                 ((stringp body)
                  (insert (string-trim-left body))
                  (unless (string-suffix-p "\n" body)
                    (insert "\n")))
                 (t
                  (prin1 body (current-buffer))
                  (insert "\n")))))
            (insert ")\n\n")))))
    (insert "(provide 'etaf-dev-autoloads)\n")
    (insert ";;; dev-autoloads.el ends here\n"))
  (setq command-line-args-left nil)
  (princ (format "%d %d\n" pkg-count form-count))))
"""


def discover_packages(root: Path, extras: list[Path]) -> list[dict[str, str]]:
    """Return ordered list of {name, dir, file} dicts; monorepo overrides extras."""
    found: dict[str, dict[str, str]] = {}
    for name, pkg_dir in workspace_layout.package_dirs(root).items():
        entry = pkg_dir / f"{name}.el"
        if entry.is_file():
            found[name] = {
                "name": name,
                "dir": str(pkg_dir.resolve()),
                "file": str(entry.resolve()),
            }
    for extra in extras:
        extra_root = extra.expanduser().resolve()
        if not extra_root.is_dir():
            continue
        for child in sorted(extra_root.iterdir()):
            if not child.is_dir() or child.name.startswith("."):
                continue
            name = child.name
            if name in found:
                continue
            entry = child / f"{name}.el"
            if entry.is_file():
                found[name] = {
                    "name": name,
                    "dir": str(child.resolve()),
                    "file": str(entry.resolve()),
                }
    return [found[k] for k in sorted(found)]


def generate(root: Path, extras: list[Path], output: Path, emacs: str) -> tuple[int, int]:
    entries = discover_packages(root, extras)
    output = output.expanduser().resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    tmp_out = output.with_suffix(output.suffix + ".tmp")
    with tempfile.NamedTemporaryFile("w", suffix=".json", encoding="utf-8", delete=False) as sf:
        json.dump({"entries": entries}, sf)
        spec_path = Path(sf.name)
    try:
        env = os.environ.copy()
        env["DEV_AUTOLOADS_SPEC"] = str(spec_path)
        env["DEV_AUTOLOADS_OUT"] = str(tmp_out)
        proc = subprocess.run(
            [emacs, "-Q", "--batch", "--eval", ELISP_GENERATOR],
            env=env,
            capture_output=True,
            text=True,
            check=False,
        )
        if proc.returncode != 0:
            sys.stderr.write(proc.stderr)
            raise SystemExit(proc.returncode)
        os.replace(tmp_out, output)
        lines = [line.strip() for line in proc.stdout.splitlines() if line.strip()]
        pkg_count, form_count = (int(x) for x in lines[-1].split()) if lines else (len(entries), 0)
        return pkg_count, form_count
    finally:
        spec_path.unlink(missing_ok=True)
        if tmp_out.exists():
            tmp_out.unlink(missing_ok=True)


ELISP_CHECKER = r"""
(progn
  (let ((autoload-file (getenv "DEV_AUTOLOADS_OUT")))
    (load autoload-file nil t)
    (when (featurep 'etaf)
      (error "dev-autoloads check failed: loading autoloads eagerly loaded `etaf'"))
    (require 'etaf)
    (let ((apps (etaf-app-list))
          (errors nil))
      (unless apps
        (push "etaf-app-list is empty after loading dev-autoloads and etaf" errors))
      (dolist (entry apps)
        (let ((id (plist-get entry :id))
              (title (plist-get entry :title))
              (open (plist-get entry :open))
              (feature (plist-get entry :feature)))
          (unless (and (symbolp id) id)
            (push (format "invalid :id in app entry: %S" entry) errors))
          (unless (and (stringp title) (not (string-empty-p title)))
            (push (format "%S: missing non-empty :title" id) errors))
          (unless (and (symbolp open) (fboundp open))
            (push (format "%S: :open %S is not fboundp/autoloaded" id open) errors))
          (when (and feature (not (locate-library (symbol-name feature))))
            (push (format "%S: :feature %S not found on load-path" id feature) errors))))
      (when errors
        (dolist (err (nreverse errors))
          (princ (format "error: %s\n" err) #'external-debugging-output))
        (kill-emacs 1))
      (princ (format "dev-autoloads check OK: zero eager load, %d registered apps validated\n"
                     (length apps))))))
"""


def check(root: Path, extras: list[Path], emacs: str) -> int:
    """Verify generated dev-autoloads loads cleanly without eager `etaf' load."""
    with tempfile.TemporaryDirectory(prefix="etaf-dev-autoloads-check-") as tmp:
        out = Path(tmp) / "dev-autoloads.el"
        pkg_count, form_count = generate(root, extras, out, emacs)
        env = os.environ.copy()
        env["DEV_AUTOLOADS_OUT"] = str(out)
        proc = subprocess.run(
            [emacs, "-Q", "--batch", "--eval", ELISP_CHECKER],
            env=env,
            capture_output=True,
            text=True,
            check=False,
        )
        if proc.stdout:
            sys.stdout.write(proc.stdout)
        if proc.returncode != 0:
            if proc.stderr:
                sys.stderr.write(proc.stderr)
            return proc.returncode
        print(f"Verified {pkg_count} packages, {form_count} autoload forms.")
        return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root",
        type=Path,
        default=SCRIPT_DIR.parent,
        help="Monorepo root directory (default: workspace root).",
    )
    parser.add_argument(
        "--extra",
        type=Path,
        action="append",
        default=[],
        help="Optional companion checkout directory to scan for non-monorepo packages.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("~/.cache/emacs-taf/dev-autoloads.el"),
        help="Output autoloads file (default: ~/.cache/emacs-taf/dev-autoloads.el).",
    )
    parser.add_argument(
        "--emacs",
        default=os.environ.get("EMACS", "emacs"),
        help="Emacs executable to invoke (default: emacs).",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Generate to a temp file and verify zero eager `etaf' load plus app registry schema.",
    )
    args = parser.parse_args(argv)
    if args.check:
        return check(args.root, args.extra, args.emacs)
    pkg_count, form_count = generate(args.root, args.extra, args.output, args.emacs)
    print(f"Generated {args.output.expanduser()} ({pkg_count} packages, {form_count} autoload forms)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
